@pytest.mark.parametrize("field", list(REQUIRED_FIELDS))
def test_missing_required_field_is_reported(tmp_path: Path, field: str) -> None:
    relative = "docs/archive/missing.md"
    kept = tuple(name for name in REQUIRED_FIELDS if name != field)
    _write(tmp_path, relative, _complete_header(*kept))
    labels = ", ".join(sorted(REQUIRED_FIELDS[field]))
    assert check_archive_provenance(tmp_path, tracked_paths={relative}) == [
        f"{relative}: missing {field} (expected one of: {labels})"
    ]


def test_archived_on_without_iso_date_is_reported(tmp_path: Path) -> None:
    relative = "docs/archive/dateless.md"
    _write(
        tmp_path,
        relative,
        _complete_header(
            "original_path",
            "reason",
            "replacement",
            "content_type",
        ).replace(
            "- Reason:",
            "- Archived: last week\n- Reason:",
        ),
    )
    assert check_archive_provenance(tmp_path, tracked_paths={relative}) == [
        f"{relative}: archived_on has no ISO date"
    ]


def test_provenance_after_header_window_is_reported(tmp_path: Path) -> None:
    relative = "docs/archive/late.md"
    filler = "\n".join(f"padding line {index}" for index in range(1, 41))
    _write(tmp_path, relative, f"{filler}\n{_complete_header(*REQUIRED_FIELDS)}")
    problems = check_archive_provenance(tmp_path, tracked_paths={relative})
    assert problems
    assert all(problem.startswith(f"{relative}: missing ") for problem in problems)
    assert len(problems) == len(REQUIRED_FIELDS)


def test_archive_readme_index_is_ignored(tmp_path: Path) -> None:
    readme = "docs/archive/README.md"
    nested = "docs/archive/product/README.md"
    valid = "docs/archive/kept.md"
    _write(tmp_path, readme, "# Index\n")
    _write(tmp_path, nested, "# Nested index\n")
    _write(tmp_path, valid, _complete_header(*REQUIRED_FIELDS))
    tracked = {readme, nested, valid}
    assert check_archive_provenance(tmp_path, tracked_paths=tracked) == []


@pytest.mark.parametrize(
    ("relative", "body", "also_tracked"),
    [
        ("docs/archive/shape-blockquote-list.md", SHAPE_BLOCKQUOTE_LIST, frozenset()),
        (
            "docs/archive/shape-plain-blockquote.md",
            SHAPE_PLAIN_BLOCKQUOTE,
            # Shape 2 carries no replacement label: its undated original path is
            # the living replacement, so it must still be tracked.
            frozenset({"docs/perf/freshness-e2e-realpath.md"}),
        ),
        ("docs/archive/shape-plain-list.md", SHAPE_PLAIN_LIST, frozenset()),
    ],
)
def test_real_world_header_shapes_pass(
    tmp_path: Path, relative: str, body: str, also_tracked: frozenset[str]
) -> None:
    _write(tmp_path, relative, body)
    tracked = {relative, *also_tracked}
    assert check_archive_provenance(tmp_path, tracked_paths=tracked) == []


