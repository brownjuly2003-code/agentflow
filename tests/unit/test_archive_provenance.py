def test_replacement_is_implied_only_by_a_tracked_original_path(tmp_path: Path) -> None:
    relative = "docs/archive/implied.md"
    header = _complete_header("original_path", "archived_on", "reason", "content_type")
    _write(tmp_path, relative, header)
    assert check_archive_provenance(tmp_path, tracked_paths={relative, "docs/example.md"}) == []
