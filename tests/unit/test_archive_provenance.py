_FIELD_LINES = {
    "original_path": "- Original path: docs/example.md",
    "archived_on": "- Archived: 2026-08-26",
    "reason": "- Reason: moved for hygiene",
    "replacement": "- Current replacement: docs/current.md",
    "content_type": "- Content type: historical narrative",
}


def _write(root: Path, relative: str, body: str) -> None:
    path = root.joinpath(*relative.split("/"))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8", newline="\n")


def _complete_header(*fields: str) -> str:
    lines = ["# Fixture", ""]
    lines.extend(_FIELD_LINES[field] for field in fields)
    lines.append("")
    return "\n".join(lines)


def test_real_archive_tree_has_provenance() -> None:
    assert check_archive_provenance(ROOT) == []
    tracked = load_tracked_paths(ROOT)
    assert tracked is not None
    archived = [path for path in tracked if is_archived_document(path)]
    assert len(archived) >= 17


